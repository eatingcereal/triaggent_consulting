#!/usr/bin/env python3
"""Keep the homepage's approved inline-script hashes in sync with the bundle."""
import base64
import hashlib
import json
import re
from pathlib import Path


def homepage_policy(source):
    template = re.search(r'<script type="__bundler/template">(.*?)</script>', source, re.S)
    if not template:
        raise ValueError('Bundled homepage template missing')
    hashes = set()
    for html in (source, json.loads(template[1])):
        for attributes, code in re.findall(r'<script\b([^>]*)>(.*?)</script\s*>', html, re.S | re.I):
            kind = re.search(r'\btype=["\']([^"\']+)', attributes, re.I)
            if re.search(r'\bsrc\s*=', attributes, re.I) or (kind and kind[1] not in ('module', 'text/javascript', 'application/javascript')):
                continue
            hashes.add("'sha256-" + base64.b64encode(hashlib.sha256(code.encode('utf-8')).digest()).decode() + "'")
    # The exported component runtime compiles its bundled component with Function.
    # Inline scripts are still hash-gated; no third-party script hosts are allowed.
    return ("default-src 'self'; script-src 'self' blob: 'unsafe-eval' " + ' '.join(sorted(hashes))
            + "; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
              "font-src 'self' data: https://fonts.gstatic.com; img-src 'self' data: blob:; "
              "connect-src 'self' blob:; object-src 'none'; base-uri 'self'; "
              "form-action 'self'; frame-src 'none'; frame-ancestors 'none'; upgrade-insecure-requests")


def update_homepage_policy(root):
    policy = homepage_policy((root / 'index.html').read_text(encoding='utf-8'))
    htaccess = root / '.htaccess'
    source = htaccess.read_text(encoding='utf-8')
    replacement = ('# homepage-csp:start (generated by scripts/security_policy.py)\n'
                   '    Header always set Content-Security-Policy "' + policy + '" env=TRIAGGENT_HOME\n'
                   '    # homepage-csp:end')
    updated, count = re.subn(r'# homepage-csp:start.*?# homepage-csp:end', lambda _: replacement, source, flags=re.S)
    if count != 1:
        raise ValueError('Expected one homepage CSP block in .htaccess')
    htaccess.write_text(updated, encoding='utf-8')


if __name__ == '__main__':
    update_homepage_policy(Path(__file__).resolve().parents[1])
    print('Updated homepage CSP hashes')
